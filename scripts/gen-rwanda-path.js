// scripts/gen-rwanda-path.js
// Converts Donor Mapping/rw.json (GeoJSON) → data/rwanda-path.js
// Projection: simple equirectangular into a 900×540 SVG viewBox.
//
// Rwanda bounds (from the GeoJSON):
//   lon 28.8572 – 30.8878   lat -2.8269 – -1.0587
//
// Rwanda fills SVG area  x ≈ 220–618   y ≈ 90–440
// Scale: 197 px / degree (approx equal-area at Rwanda's latitude)

'use strict';
const fs   = require('fs');
const path = require('path');

const GEO   = path.join(__dirname, '..', 'Donor Mapping', 'rw.json');
const OUT   = path.join(__dirname, '..', 'data', 'rwanda-path.js');

const LON_MIN = 28.8572;
const LAT_MAX = -1.0587;   // northernmost lat  →  minimum SVG y
const SCALE   = 197;       // px per degree
const X_OFF   = 220;
const Y_OFF   = 90;

function project([lon, lat]) {
  const x = (X_OFF + (lon - LON_MIN) * SCALE).toFixed(1);
  const y = (Y_OFF + (LAT_MAX - lat) * SCALE).toFixed(1);
  return `${x} ${y}`;
}

function ringToPath(ring) {
  const pts = ring.map(project);
  return 'M ' + pts.join(' L ') + ' Z';
}

const geojson = JSON.parse(fs.readFileSync(GEO, 'utf8'));
let d = '';

geojson.features.forEach(feature => {
  const { type, coordinates } = feature.geometry;
  const polys = type === 'Polygon' ? [coordinates] : coordinates;
  polys.forEach(poly => {
    poly.forEach(ring => { d += ringToPath(ring) + ' '; });
  });
});

d = d.trim();

const output = [
  '// AUTO-GENERATED by scripts/gen-rwanda-path.js — do not edit by hand.',
  '// Re-run: node scripts/gen-rwanda-path.js',
  `window.__RWANDA_PATH = ${JSON.stringify(d)};`,
  '',
].join('\n');

fs.writeFileSync(OUT, output, 'utf8');
console.log(`Generated data/rwanda-path.js  (${d.length} chars, ${geojson.features.length} feature(s))`);
